// twoDirectives is a source file declaring two value objects.
const twoDirectives = "//vogue:string CountryCode required\n//vogue:id GeoNamesID int64\n"

func TestGenerator_FileNames(t *testing.T) {
	t.Run("names the files after the source file and the default suffix", func(t *testing.T) {
		// Arrange
		pkg := parseSource(t, twoDirectives, testrules.Set(testrulesPath))

		// Act
		files, err := filesOf(t, gen.Options{Validation: testValidation, Package: pkg})

		// Assert
		require.NoError(t, err)
		assert.Equal(t, []string{"vo_vogue.go", "vo_vogue_test.go"}, baseNames(files))
	})

	t.Run("names the files after the source file and a custom suffix", func(t *testing.T) {
		// Arrange
		pkg := parseSource(t, twoDirectives, testrules.Set(testrulesPath))

		// Act
		files, err := filesOf(t, gen.Options{Validation: testValidation, Package: pkg, Suffix: "_gen"})

		// Assert
		require.NoError(t, err)
		assert.Equal(t, []string{"vo_gen.go", "vo_gen_test.go"}, baseNames(files))
	})

	t.Run("writes one file per value object, named after it, without a suffix", func(t *testing.T) {
		// Arrange
		pkg := parseSource(t, twoDirectives, testrules.Set(testrulesPath))

		// Act
		files, err := filesOf(t, gen.Options{Validation: testValidation, Package: pkg, PerValueObject: true})

		// Assert
		require.NoError(t, err)
		assert.Equal(t, []string{
			"country_code.go", "country_code_test.go", "geo_names_id.go", "geo_names_id_test.go",
		}, baseNames(files))
		assert.Contains(t, string(files[0].Content), "type CountryCode struct")
		assert.NotContains(t, string(files[0].Content), "GeoNamesID")
		assert.Contains(t, string(files[3].Content), "func TestGeoNamesID_ZeroHasNoText(")
	})
}

func TestWrite_Ownership(t *testing.T) {
	t.Run("refuses to overwrite a file vogue did not generate, and writes nothing", func(t *testing.T) {
		// Arrange
		dir := t.TempDir()
		mine := filepath.Join(dir, "country_code.go")
		require.NoError(t, os.WriteFile(mine, []byte("package x\n\n// hand-written\n"), 0o600))
		other := filepath.Join(dir, "other.go")
		files := []gen.OutFile{
			{Path: other, Content: []byte(gen.Header + "\n\npackage x\n")},
			{Path: mine, Content: []byte(gen.Header + "\n\npackage x\n")},
		}

		// Act
		err := gen.Write(files)

		// Assert
		require.ErrorIs(t, err, gen.ErrNotGenerated)
		kept, readErr := os.ReadFile(mine)
		require.NoError(t, readErr)
		assert.Equal(t, "package x\n\n// hand-written\n", string(kept))
		assert.NoFileExists(t, other, "nothing is written when one file is refused")
	})

	t.Run("overwrites a file it generated", func(t *testing.T) {
		// Arrange
		dir := t.TempDir()
		path := filepath.Join(dir, "vo_vogue.go")
		require.NoError(t, os.WriteFile(path, []byte(gen.Header+"\n\npackage x\n// old\n"), 0o600))

		// Act
		err := gen.Write([]gen.OutFile{{Path: path, Content: []byte(gen.Header + "\n\npackage x\n")}})

		// Assert
		require.NoError(t, err)
		got, readErr := os.ReadFile(path)
		require.NoError(t, readErr)
		assert.Equal(t, gen.Header+"\n\npackage x\n", string(got))
	})
}

func TestStale(t *testing.T) {
	t.Run("finds the generated files a run no longer writes, and only those", func(t *testing.T) {
		// Arrange
		dir := t.TempDir()
		write := func(name, content string) string {
			path := filepath.Join(dir, name)
			require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
			return path
		}
		generated := gen.Header + "\n\npackage x\n"
		kept := write("vo_vogue.go", generated)
		stale := write("old_vogue.go", generated)
		staleTest := write("old_vogue_test.go", generated)
		write("hand.go", "package x\n")
		write("other_gen.go", "// Code generated by stringer. DO NOT EDIT.\n\npackage x\n")
		write("notes.txt", generated)

		// Act
		got, err := gen.Stale(dir, []gen.OutFile{{Path: kept}})

		// Assert
		require.NoError(t, err)
		assert.ElementsMatch(t, []string{stale, staleTest}, got)
	})
}

// baseNames returns the base names of the files, in order.
func baseNames(files []gen.OutFile) []string {
	names := make([]string, len(files))
	for i, file := range files {
		names[i] = filepath.Base(file.Path)
	}
	return names
}
