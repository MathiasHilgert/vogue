// templates holds the source templates, one per generated shape plus the file
// header. They are embedded so the generator is a single binary with no runtime
// dependency on its own source tree.
//
//go:embed templates/*.tmpl
var templates embed.FS

// DefaultSuffix is appended to the base name of a source file to name the file
// generated from it, when [Options.Suffix] is empty and
// [Options.PerValueObject] is not set.
const DefaultSuffix = "_vogue"

// Header is the first line of every file vogue generates, in the form
// golang.org/s/generatedcode prescribes. vogue overwrites and removes only
// files that start with it.
const Header = "// Code generated by vogue. DO NOT EDIT."

// ErrNotGenerated is wrapped by [Write] when a destination exists but does not
// start with [Header]: the file belongs to someone else, and vogue refuses to
// overwrite it.
var ErrNotGenerated = errors.New("the file was not generated by vogue")

// FileKind tells a generated file apart from the test that proves it, so a
// caller can write, diff or skip one of the two without matching on the name.
type FileKind uint8

const (
	// CodeFile is a generated value-object source file.
	CodeFile FileKind = iota
	// TestFile is the generated test of a [CodeFile].
	TestFile
)

// String returns the name of the file kind.
func (k FileKind) String() string {
	switch k {
	case CodeFile:
		return "code"
	case TestFile:
		return "test"
	default:
		return fmt.Sprintf("FileKind(%d)", uint8(k))
	}
}

// Options configures a [Generator].
type Options struct {
	// Package is the parsed package to generate from. It is required.
	Package *parse.Package
	// Rules is the catalogue the directives were parsed against. The generator
	// reads the rules off the directives themselves, so this is carried for the
	// test generator and the CLI rather than used here.
	Rules *vogue.RuleSet
	// ImportPath is the import path of the package being generated into. When a
	// rule dispatches to a function in that same package, the call is emitted
	// unqualified and the package is not imported into itself. It may be empty.
	ImportPath string
	// Suffix is appended to the base name of a source file to name the files
	// generated from it: "_vogue" writes vo_vogue.go and vo_vogue_test.go
	// next to vo.go. Empty means [DefaultSuffix].
	Suffix string
	// PerValueObject writes one file and one test per value object instead,
	// named after it in snake case with no suffix: CountryCode is written to
	// country_code.go and country_code_test.go. Suffix is ignored.
	PerValueObject bool
	// OmitSQL leaves the database/sql/driver codec (Value and Scan) out of
	// the generated code. A hexagonal domain package that must not import
	// database/sql/driver sets it and converts at the persistence adapter
	// through the text codec or the accessors instead.
	OmitSQL bool
	// Schema adds a JSONSchema method to every value object, returning the
	// neutral github.com/MathiasHilgert/vogue/schema description an HTTP
	// adapter publishes in its OpenAPI document.
	Schema bool
}

// OutFile is one generated file: the path it belongs at and its formatted
// content. Nothing is written until the caller asks for it, so a generator run
// can be inspected, diffed or discarded.
type OutFile struct {
	// Kind says whether the file holds value objects or their tests.
	Kind FileKind
	// Path is the destination path of the file.
	Path string
	// Content is the gofmt-clean source.
	Content []byte
}

// Generator renders the value objects of one parsed package.
type Generator struct {
	opts Options
	tmpl *template.Template
}

// New validates the options and prepares the templates.
func New(opts Options) (*Generator, error) {
	if opts.Package == nil {
		return nil, fmt.Errorf("gen: package must not be nil")
	}
	if opts.Package.Name == "" {
		return nil, fmt.Errorf("gen: package name must not be empty")
	}

	tmpl, err := template.New("vogue").Funcs(template.FuncMap{"q": quote}).ParseFS(templates, "templates/*.tmpl")
	if err != nil {
		return nil, fmt.Errorf("gen: loading templates: %w", err)
	}
	return &Generator{opts: opts, tmpl: tmpl}, nil
}

// Files renders, for every source file that declares at least one directive,
// the value objects it declares and the test that proves them. The pair is
// returned in that order, tagged with [FileKind]. Source files without
// directives produce nothing, so the generator never leaves an empty file
// behind.
func (g *Generator) Files() ([]OutFile, error) {
	var out []OutFile
	for _, unit := range g.units() {
		content, err := g.file(unit.source)
		if err != nil {
			return nil, err
		}
		out = append(out, OutFile{Kind: CodeFile, Path: unit.code, Content: content})

		test, err := g.testFile(unit.source)
		if err != nil {
			return nil, err
		}
		out = append(out, OutFile{Kind: TestFile, Path: unit.test, Content: test})
	}
	return hoistTests(out)
}

// hoistTests names the strings the generated tests of the package repeat,
// counting across all of them, as goconst does.
func hoistTests(files []OutFile) ([]OutFile, error) {
	var (
		sources [][]byte
		at      []int
	)
	for i, file := range files {
		if file.Kind == TestFile {
			sources = append(sources, file.Content)
			at = append(at, i)
		}
	}
	hoisted, err := hoistRepeatedStrings(sources)
	if err != nil {
		return nil, err
	}
	for j, i := range at {
		files[i].Content = hoisted[j]
	}
	return files, nil
}

// file renders and formats one generated file.
func (g *Generator) file(file parse.File) ([]byte, error) {
	imports := newImportSet(g.opts.ImportPath)
	decls := newDeclSet()

	var bodies bytes.Buffer
	for _, directive := range file.Directives {
		view, name, err := g.newView(directive, imports, decls)
		if err != nil {
			return nil, err
		}
		if err := g.tmpl.ExecuteTemplate(&bodies, name+".tmpl", view); err != nil {
			return nil, fmt.Errorf("gen: rendering %s: %w", directive.Name, err)
		}
	}

	var buf bytes.Buffer
	std, ext := imports.groups()
	header := fileView{Package: g.opts.Package.Name, Std: std, Ext: ext, Decls: decls.all()}
	if err := g.tmpl.ExecuteTemplate(&buf, "header.tmpl", header); err != nil {
		return nil, fmt.Errorf("gen: rendering header of %s: %w", file.Path, err)
	}
	buf.Write(bodies.Bytes())

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: formatting %s: %w\n%s", file.Path, err, buf.String())
	}
	return formatted, nil
}

// unit is the directives rendered into one generated file and its test.
type unit struct {
	source     parse.File
	code, test string
}

// units groups the directives of the package into the files they are written
// to: one per source file with directives, or one per value object.
func (g *Generator) units() []unit {
	var out []unit
	for _, file := range g.opts.Package.Files {
		if len(file.Directives) == 0 {
			continue
		}
		dir := filepath.Dir(file.Path)
		if !g.opts.PerValueObject {
			suffix := g.opts.Suffix
			if suffix == "" {
				suffix = DefaultSuffix
			}
			base := strings.TrimSuffix(filepath.Base(file.Path), ".go") + suffix
			out = append(out, unit{
				source: file,
				code:   filepath.Join(dir, base+".go"),
				test:   filepath.Join(dir, base+"_test.go"),
			})
			continue
		}
		for _, directive := range file.Directives {
			base := parse.SnakeName(directive.Name)
			out = append(out, unit{
				source: parse.File{Path: file.Path, Directives: []parse.Directive{directive}},
				code:   filepath.Join(dir, base+".go"),
				test:   filepath.Join(dir, base+"_test.go"),
			})
		}
	}
	return out
}

// Write writes every file to its path. Each one is written to a temporary file
// in the destination directory and renamed into place, so a failed or
// interrupted run never leaves a half-written source file behind.
//
// A destination that exists and does not start with [Header] is refused with
// [ErrNotGenerated] before anything is written, so a run that would clobber a
// hand-written file changes nothing.
func Write(files []OutFile) error {
	for _, file := range files {
		owned, err := ownedOrAbsent(file.Path)
		if err != nil {
			return err
		}
		if !owned {
			return fmt.Errorf("gen: refusing to overwrite %s: it does not start with %q: %w", file.Path, Header, ErrNotGenerated)
		}
	}
	for _, file := range files {
		if err := writeAtomic(file); err != nil {
			return err
		}
	}
	return nil
}

// writeAtomic writes one file through a temporary file and a rename.
func writeAtomic(file OutFile) error {
	dir := filepath.Dir(file.Path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(file.Path)+".*")
	if err != nil {
		return fmt.Errorf("gen: creating temporary file for %s: %w", file.Path, err)
	}
	// The temporary file is removed on every path; once the rename succeeded
	// there is nothing left at that name, and the failure is not actionable.
	defer func() { _ = os.Remove(tmp.Name()) }()

	if _, err := tmp.Write(file.Content); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("gen: writing %s: %w", file.Path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("gen: closing %s: %w", file.Path, err)
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return fmt.Errorf("gen: setting mode of %s: %w", file.Path, err)
	}
	if err := os.Rename(tmp.Name(), file.Path); err != nil {
		return fmt.Errorf("gen: renaming into %s: %w", file.Path, err)
	}
	return nil
}

// quote renders a string as a Go literal.
func quote(s string) string { return strconv.Quote(s) }

// ownedOrAbsent reports whether path may be written: it does not exist, or it
// is a file vogue generated.
func ownedOrAbsent(path string) (bool, error) {
	content, err := os.ReadFile(path) //nolint:gosec // the path is one the generator derived.
	if errors.Is(err, fs.ErrNotExist) {
		return true, nil
	}
	if err != nil {
		return false, fmt.Errorf("gen: reading %s: %w", path, err)
	}
	return IsGenerated(content), nil
}

// IsGenerated reports whether a Go source file was generated by vogue: its
// first line is [Header].
func IsGenerated(content []byte) bool {
	first, _, _ := strings.Cut(string(content), "\n")
	return strings.TrimRight(first, "\r") == Header
}

// Stale returns the Go files of dir that vogue generated and that are not
// among files, which is what a previous run wrote and this one no longer
// does: the files of a removed directive, or of a suffix since changed. A
// file without [Header] is never returned, whatever its name.
func Stale(dir string, files []OutFile) ([]string, error) {
	keep := make(map[string]struct{}, len(files))
	for _, file := range files {
		keep[filepath.Clean(file.Path)] = struct{}{}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("gen: reading %s: %w", dir, err)
	}
	var stale []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		if _, kept := keep[filepath.Clean(path)]; kept {
			continue
		}
		content, err := os.ReadFile(path) //nolint:gosec // a file of the directory being generated.
		if err != nil {
			return nil, fmt.Errorf("gen: reading %s: %w", path, err)
		}
		if IsGenerated(content) {
			stale = append(stale, path)
		}
	}
	return stale, nil
}
